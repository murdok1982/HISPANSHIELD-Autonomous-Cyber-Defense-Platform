ALLOWED_CHECK_TYPES = frozenset(
    {
        "mfa_enforced",
        "audit_chain_valid",
        "connector_tls",
        "backup_configured",
        "retention_policy_days",
        "incident_process_exists",
        "vulnerability_sla",
        "asset_inventory_coverage",
        "ot_passive_only",
        "supplier_register",
        "encryption_at_rest",
        "rbac_least_privilege",
        "session_timeout",
        "logging_enabled",
        "patch_management",
        "network_segmentation",
        "access_review",
        "data_minimisation",
    }
)

CONTROL_STATUSES = ("compliant", "partial", "non_compliant", "not_applicable")
CONTROL_STATUS_VALUES = frozenset({*CONTROL_STATUSES, "not_assessed"})

KEY_PATTERN = r"^[a-z0-9][a-z0-9_.-]{0,59}$"
CONTROL_ID_PATTERN = r"^[A-Za-z0-9][A-Za-z0-9._:-]{0,39}$"
CODE_PATTERN = r"^[A-Za-z0-9][A-Za-z0-9 ._:/-]{0,39}$"

DISCLAIMER = (
    "Technical self-assessment - not a certification. Generated by HISPANSHIELD from platform "
    "evidence; it is not an accreditation, audit opinion or legal advice."
)


class EvidenceRequirementDoc(StrictModel):
    key: str = Field(min_length=1, max_length=60, pattern=KEY_PATTERN)
    title: str = Field(min_length=1, max_length=200)
    description: str = Field(min_length=1, max_length=1000)


class TechnicalCheckDoc(StrictModel):
    key: str = Field(min_length=1, max_length=60, pattern=KEY_PATTERN)
    title: str = Field(min_length=1, max_length=200)
    type: str = Field(min_length=1, max_length=40)
    params: dict[str, Any] = Field(default_factory=dict)
    description: str = Field(default="", max_length=1000)

    @field_validator("type")
    @classmethod
    def _known_type(cls, value: str) -> str:
        if value not in ALLOWED_CHECK_TYPES:
            raise ValueError(f"Unknown technical check type: {value}")
        return value

    @field_validator("params")
    @classmethod
    def _scalar_params(cls, value: dict[str, Any]) -> dict[str, Any]:
        if len(value) > 20:
            raise ValueError("Too many check parameters")
        for key, item in value.items():
            if not isinstance(key, str) or len(key) > 40:
                raise ValueError("Invalid parameter name")
            if isinstance(item, dict | list):
                raise ValueError("Check parameters must be scalar values")
            if isinstance(item, str) and len(item) > 200:
                raise ValueError("Check parameter value too long")
        return value


class ControlDoc(StrictModel):
    control_id: str = Field(min_length=1, max_length=40, pattern=CONTROL_ID_PATTERN)
    title: str = Field(min_length=1, max_length=300)
    description: str = Field(min_length=1, max_length=4000)
    category: str = Field(default="general", min_length=1, max_length=120)
    weight: int = Field(default=2, ge=1, le=5)
    references: list[str] = Field(default_factory=list, max_length=30)
    evidence_requirements: list[EvidenceRequirementDoc] = Field(default_factory=list, max_length=20)
    technical_checks: list[TechnicalCheckDoc] = Field(default_factory=list, max_length=20)
    mapping: dict[str, Any] = Field(default_factory=dict)

    @field_validator("references")
    @classmethod
    def _bounded_references(cls, value: list[str]) -> list[str]:
        cleaned: list[str] = []
        for item in value:
            text = item.strip()
            if not text:
                continue
            if len(text) > 200:
                raise ValueError("Reference entry too long")
            cleaned.append(text)
        return cleaned

    @model_validator(mode="after")
    def _unique_keys(self) -> ControlDoc:
        check_keys = [check.key for check in self.technical_checks]
        if len(check_keys) != len(set(check_keys)):
            raise ValueError(f"Duplicate technical check key in control {self.control_id}")
        evidence_keys = [item.key for item in self.evidence_requirements]
        if len(evidence_keys) != len(set(evidence_keys)):
            raise ValueError(f"Duplicate evidence key in control {self.control_id}")
        return self


class FrameworkDocument(StrictModel):
    """A versioned framework catalogue document (YAML or JSON)."""

    code: str = Field(min_length=2, max_length=40, pattern=CODE_PATTERN)
    name: str = Field(min_length=2, max_length=200)
    version: str = Field(min_length=1, max_length=40)
    jurisdiction: str = Field(default="EU", min_length=2, max_length=80)
    authority: str | None = Field(default=None, max_length=200)
    effective_date: date | None = None
    source_url: str | None = Field(default=None, max_length=500)
    description: str | None = Field(default=None, max_length=8000)
    status: Literal["published", "draft", "retired"] = "published"
    controls: list[ControlDoc] = Field(min_length=1, max_length=500)

    @field_validator("source_url")
    @classmethod
    def _http_url(cls, value: str | None) -> str | None:
        if value is None:
            return None
        if not (value.startswith("https://") or value.startswith("http://")):
            raise ValueError("source_url must be an http(s) URL")
        return value

    @model_validator(mode="after")
    def _unique_control_ids(self) -> FrameworkDocument:
        ids = [control.control_id for control in self.controls]
        if len(ids) != len(set(ids)):
            raise ValueError("Duplicate control_id within framework")
        return self


